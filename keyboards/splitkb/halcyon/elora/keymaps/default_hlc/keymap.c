bool process_record_user(uint16_t keycode, keyrecord_t *record) {
    switch (keycode) {
    case MY_ARR:
        if (record->event.pressed) {
            SEND_STRING("=>");
        }
        break;
    case MY_TMP:
        if (record->event.pressed) {
            SEND_STRING("${");
        }
        break;
    case MY_LANG:
        if (record->event.pressed) {
            register_code(KC_LCTL);
            register_code(KC_SPC);
            unregister_code(KC_SPC);
            unregister_code(KC_LCTL);
        }
        break;
    }
    return true;
};

